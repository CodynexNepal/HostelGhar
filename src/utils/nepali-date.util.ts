const BS_BASE_YEAR = 2000;
const BS_BASE_AD_UTC_MS = Date.UTC(1943, 3, 14);
const DAY_MS = 24 * 60 * 60 * 1000;

const isSupportedBsYear = (year: number): boolean =>
  Number.isInteger(year) && year >= BS_BASE_YEAR && year < BS_BASE_YEAR + BS_CALENDAR.length;

export const getBsMonthLength = (bsYear: number, bsMonth: number): number => {
  if (!isSupportedBsYear(bsYear) || bsMonth < 1 || bsMonth > 12) return 30;
  const row = BS_CALENDAR[bsYear - BS_BASE_YEAR];
  return row?.[bsMonth - 1] ?? 30;
};

/** Convert an AD date (UTC day precision) to Bikram Sambat. */
export const toNepaliDate = (date: Date = new Date()): NepaliDate => {
  const adUtc = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  let days = Math.floor((adUtc - BS_BASE_AD_UTC_MS) / DAY_MS);
  if (days < 0) days = 0;

  let bsYear = BS_BASE_YEAR;
  let remaining = days;
  while (bsYear < BS_BASE_YEAR + BS_CALENDAR.length) {
    const row = BS_CALENDAR[bsYear - BS_BASE_YEAR] as number[];
    const yearDays = row.reduce((a, b) => a + b, 0);
    if (remaining < yearDays) break;
    remaining -= yearDays;
    bsYear += 1;
  }
  if (bsYear >= BS_BASE_YEAR + BS_CALENDAR.length) {
    bsYear = BS_BASE_YEAR + BS_CALENDAR.length - 1;
    const last = BS_CALENDAR[bsYear - BS_BASE_YEAR] as number[];
    remaining = last.reduce((a, b) => a + b, 0) - 1;
  }

  const months = BS_CALENDAR[bsYear - BS_BASE_YEAR] as number[];
  let bsMonth = 1;
  let dayLeft = remaining;
  for (let i = 0; i < 12; i += 1) {
    const len = months[i] as number;
    if (dayLeft < len) {
      bsMonth = i + 1;
      break;
    }
    dayLeft -= len;
    if (i === 11) bsMonth = 12;
  }
  return { year: bsYear, month: bsMonth, day: dayLeft + 1 };
};

/** True when the given AD date is the 1st day of a Nepali month. */
export const isFirstDayOfNepaliMonth = (date: Date = new Date()): boolean =>
  toNepaliDate(date).day === 1;

/** "Ashwin 2083" style billing label. */
export const formatNepaliMonthYear = (bs: NepaliDate): string => {
  const name = NEPALI_MONTHS_EN[(bs.month - 1) % 12] ?? `Month ${bs.month}`;
  return `${name} ${bs.year}`;
};

/** "1 Ashwin 2083 BS" style full date. */
export const formatNepaliDate = (bs: NepaliDate): string =>
  `${bs.day} ${formatNepaliMonthYear(bs)} BS`;
